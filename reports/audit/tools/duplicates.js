#!/usr/bin/env node
/* 5-word-shingle Jaccard similarity within and across templates → duplicates.md */
const fs = require('fs');
const path = require('path');
const TOOLS = __dirname;
const idx = JSON.parse(fs.readFileSync(path.join(TOOLS, 'corpus-index.json'), 'utf8'));

function shingles(text, k = 5) {
  const toks = text.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean);
  const s = new Set();
  for (let i = 0; i + k <= toks.length; i++) s.add(toks.slice(i, i + k).join(' '));
  return s;
}
function jaccard(a, b) {
  if (!a.size || !b.size) return 0;
  let inter = 0; const [small, big] = a.size < b.size ? [a, b] : [b, a];
  for (const x of small) if (big.has(x)) inter++;
  return inter / (a.size + b.size - inter);
}

// load text + shingles per path
const byTpl = {};
const sh = {};
for (const [p, info] of Object.entries(idx)) {
  if (info.error) continue;
  const text = fs.readFileSync(path.join(TOOLS, 'corpus', info.file), 'utf8');
  sh[p] = shingles(text);
  (byTpl[info.template] = byTpl[info.template] || []).push(p);
}

function analyzeTemplate(tpl) {
  const paths = (byTpl[tpl] || []).slice().sort();
  const n = paths.length;
  if (n < 2) return { tpl, n, note: 'single instance' };
  let pairs = 0, over80 = 0, over90 = 0, sum = 0, max = 0, maxPair = null;
  const pageMax = new Map(paths.map((p) => [p, 0]));
  // cap pairwise for very large sets by sampling if needed (not needed <=250)
  for (let i = 0; i < n; i++) {
    for (let j = i + 1; j < n; j++) {
      const s = jaccard(sh[paths[i]], sh[paths[j]]);
      pairs++; sum += s;
      if (s > 0.8) over80++;
      if (s > 0.9) over90++;
      if (s > max) { max = s; maxPair = [paths[i], paths[j]]; }
      if (s > pageMax.get(paths[i])) pageMax.set(paths[i], s);
      if (s > pageMax.get(paths[j])) pageMax.set(paths[j], s);
    }
  }
  const pagesWithDup80 = [...pageMax.values()].filter((v) => v > 0.8).length;
  const pagesWithDup90 = [...pageMax.values()].filter((v) => v > 0.9).length;
  return {
    tpl, n, pairs,
    meanJaccard: +(sum / pairs).toFixed(3),
    maxJaccard: +max.toFixed(3),
    maxPair,
    pairsOver80: over80, pairsOver80Pct: +(100 * over80 / pairs).toFixed(1),
    pairsOver90: over90,
    pagesWithNearDup80: pagesWithDup80, pagesWithNearDup80Pct: +(100 * pagesWithDup80 / n).toFixed(1),
    pagesWithNearDup90: pagesWithDup90,
  };
}

const templates = ['scenario', 'city', 'weapon', 'compare', 'glossary', 'blog'];
const results = templates.map(analyzeTemplate);

// scenario vs its matching city page
let scVsCity = [];
for (const sp of (byTpl['scenario'] || [])) {
  const slug = sp.replace('/scenarios/', '');
  const m = slug.split('-on-');
  if (m.length < 2) continue;
  const cityslug = m.slice(1).join('-on-');
  const cp = '/examples/' + cityslug;
  if (sh[cp]) scVsCity.push({ scenario: sp, city: cp, jaccard: +jaccard(sh[sp], sh[cp]).toFixed(3) });
}
const scCityVals = scVsCity.map((x) => x.jaccard).sort((a, b) => a - b);
const scCityMean = scCityVals.length ? +(scCityVals.reduce((a, b) => a + b, 0) / scCityVals.length).toFixed(3) : 0;
const scCityMax = scCityVals.length ? scCityVals[scCityVals.length - 1] : 0;
const scCityOver50 = scCityVals.filter((v) => v > 0.5).length;

// build markdown
let md = `# Thin & Duplicate Content — reports/audit/duplicates.md\n\n`;
md += `_Method: visible text per page (nav/header/footer/script stripped), 5-word shingles, Jaccard similarity. Generated by reports/audit/tools/duplicates.js over the live crawl corpus (498 pages)._\n\n`;
md += `## Word-count distribution (visible, chrome excluded)\n\n`;
md += `| template | n | min | median | max | <300 | <500 |\n|---|---|---|---|---|---|---|\n`;
const wc = JSON.parse(fs.readFileSync(path.join(TOOLS, '..', 'analysis.json'), 'utf8')).wcStats;
for (const t of ['home','blog','city','scenario','compare','weapon','glossary','hub','legal']) {
  if (!wc[t]) continue;
  md += `| ${t} | ${wc[t].n} | ${wc[t].min} | ${wc[t].median} | ${wc[t].max} | ${wc[t].under300} | ${wc[t].under500} |\n`;
}
md += `\n## Within-template near-duplicate similarity\n\n`;
md += `| template | n | pairs | mean J | max J | pairs >0.8 | % pairs >0.8 | pages w/ a ≥0.8 twin | % pages ≥0.8 | pages ≥0.9 |\n|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of results) {
  if (r.note) { md += `| ${r.tpl} | ${r.n} | — | — | — | — | — | — | — | — |\n`; continue; }
  md += `| ${r.tpl} | ${r.n} | ${r.pairs} | ${r.meanJaccard} | ${r.maxJaccard} | ${r.pairsOver80} | ${r.pairsOver80Pct}% | ${r.pagesWithNearDup80} | ${r.pagesWithNearDup80Pct}% | ${r.pagesWithNearDup90} |\n`;
}
md += `\n### Most-similar pair per template\n\n`;
for (const r of results) {
  if (r.maxPair) md += `- **${r.tpl}** — J=${r.maxJaccard}: \`${r.maxPair[0]}\` ↔ \`${r.maxPair[1]}\`\n`;
}
md += `\n## Scenario page vs its matching city page\n\n`;
md += `Matched ${scVsCity.length} scenario→city pairs (scenario slug \`{bomb}-on-{city}\` → \`/examples/{city}\`).\n\n`;
md += `- mean Jaccard: **${scCityMean}**, max: **${scCityMax}**, pairs >0.5: **${scCityOver50}/${scVsCity.length}**\n`;
md += `- interpretation: low value = scenario prose is distinct from the city page; high value = overlap/cannibalization risk.\n\n`;
md += `Sample (first 8):\n\n`;
for (const x of scVsCity.slice(0, 8)) md += `- J=${x.jaccard} \`${x.scenario}\` vs \`${x.city}\`\n`;

fs.writeFileSync(path.join(TOOLS, '..', 'duplicates.md'), md);
console.log('duplicates.md written');
for (const r of results) console.log(JSON.stringify(r));
console.log('scenario-vs-city: mean', scCityMean, 'max', scCityMax, 'over0.5', scCityOver50, '/', scVsCity.length);
