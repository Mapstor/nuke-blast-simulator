// NBS-008: generate src/lib/data/livePages.ts — the set of pages that have a
// live route, derived from research/page-map.csv (status=live). The fold
// (NBS-008) removed the city/compare/glossary pages without measured demand;
// these lists are what generateStaticParams, the sitemap and the search index
// are allowed to emit. Edit page-map.csv + rerun, never hand-edit the output.
import { writeFileSync } from 'node:fs'
import { readCsvObjects } from './lib/csv.mjs'

const rows = readCsvObjects('research/page-map.csv')
const live = rows.filter((r) => r.status === 'live').map((r) => r.slug)

const stripPrefix = (p) =>
  live.filter((s) => s.startsWith(p + '/')).map((s) => s.slice(p.length + 1)).sort()

const keptCity = stripPrefix('examples')
const keptCompare = stripPrefix('compare')
const keptGlossary = stripPrefix('glossary')

// Every live page as a route path ('home' -> '/', else '/'+slug).
const livePaths = live.map((s) => (s === 'home' ? '/' : `/${s}`)).sort()

const arr = (name, items) =>
  `export const ${name}: string[] = [\n${items.map((s) => `  '${s}',`).join('\n')}\n]`

const out = `// GENERATED by scripts/build-live-pages.mjs from research/page-map.csv — do not edit.
// The live-route set after the NBS-008 fold. Regenerate: node scripts/build-live-pages.mjs

${arr('KEPT_CITY_SLUGS', keptCity)}

${arr('KEPT_COMPARE_SLUGS', keptCompare)}

${arr('KEPT_GLOSSARY_SLUGS', keptGlossary)}

${arr('LIVE_PATHS', livePaths)}
`

writeFileSync('src/lib/data/livePages.ts', out)
console.log(
  `live pages: ${live.length} | cities ${keptCity.length} | compare ${keptCompare.length} | glossary ${keptGlossary.length}`,
)
