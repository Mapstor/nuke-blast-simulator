// NBS-012: generate src/lib/data/countries.ts from research/country-facts.csv.
// ONLY rows with status === 'verified' are emitted — candidate and gap rows
// never reach a page as facts (data-sourcing hard rule). No number is typed
// into a page: every figure on a country page comes from a row here, and every
// blast radius is computed by the engine from a yield extracted here.
//
// Warhead yields for the "blast radius of {country}'s warheads" section are
// extracted from the delivery rows' `warhead_yield` field; test yields (the
// fallback when a country has no verified warhead yield) from the tests.*yield*
// rows. Ranges (A–B), uncertain (?, <, "up to", "multi") and unit-less values
// are skipped so only clean single yields drive the engine.
// Regenerate: node scripts/build-countries.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { readCsvObjects } from './lib/csv.mjs'

const META = {
  'united-states': { name: 'United States', article: 'the', demonym: "the United States'" },
  russia: { name: 'Russia', article: '', demonym: "Russia's" },
  china: { name: 'China', article: '', demonym: "China's" },
  'united-kingdom': { name: 'United Kingdom', article: 'the', demonym: "the United Kingdom's" },
  france: { name: 'France', article: '', demonym: "France's" },
  india: { name: 'India', article: '', demonym: "India's" },
  pakistan: { name: 'Pakistan', article: '', demonym: "Pakistan's" },
  'north-korea': { name: 'North Korea', article: '', demonym: "North Korea's" },
  israel: { name: 'Israel', article: '', demonym: "Israel's" },
  iran: { name: 'Iran', article: '', demonym: "Iran's" },
}
// Canonical order: NPT-5, then the other possessors, then Iran (status page).
const ORDER = ['united-states', 'russia', 'china', 'united-kingdom', 'france',
  'india', 'pakistan', 'north-korea', 'israel', 'iran']

// Extract clean single kt yields appearing inline as "N kt" / "N MT" in text
// (used for delivery warhead_yield). Skips ranges/uncertain via lookbehind.
const INLINE = /(?<![–\-\d<.])(\d+(?:\.\d+)?)\s*(kt|MT)\b/g
function inlineYields(text) {
  const out = []
  let m
  INLINE.lastIndex = 0
  while ((m = INLINE.exec(text)) !== null) {
    let v = parseFloat(m[1])
    if (m[2] === 'MT') v *= 1000
    if (v > 0) out.push(v)
  }
  return out
}
// Parse a test-yield VALUE (unit is kt in its own column): a leading clean
// single number, rejecting ranges and <, "up to", etc.
function testYield(value) {
  const v = value.trim()
  if (/[–]|(?<=\d)\s*-\s*(?=\d)|<|≤|up to|multi/i.test(v)) return null
  const m = v.match(/(\d+(?:\.\d+)?)/)
  if (!m) return null
  const n = parseFloat(m[1])
  return n > 0 ? n : null
}

const rows = readCsvObjects('research/country-facts.csv').filter((r) => r.status.trim() === 'verified')

const countries = {}
for (const key of ORDER) {
  countries[key] = { slug: key, key, ...META[key], rows: [], warheadYieldsKt: [], testYieldsKt: [] }
}

for (const r of rows) {
  const c = countries[r.country]
  if (!c) continue // World rows handled by the hub, not a country page
  const row = {
    field: r.field, value: r.value, unit: r.unit, asOf: r.as_of,
    sourceId: r.source_id, deepUrl: r.deep_url, quote: r.quote, notes: r.notes,
  }
  c.rows.push(row)
  if (r.field.startsWith('delivery.')) {
    const cell = r.value.split('|').find((s) => s.includes('warhead_yield='))
    if (cell) for (const y of inlineYields(cell)) c.warheadYieldsKt.push(y)
  }
  if (/^tests\..*yield/.test(r.field) && /\bkt\b/i.test(r.unit)) {
    const y = testYield(r.value)
    if (y != null) c.testYieldsKt.push(y)
  }
}

for (const c of Object.values(countries)) {
  c.warheadYieldsKt = [...new Set(c.warheadYieldsKt)].sort((a, b) => a - b)
  c.testYieldsKt = [...new Set(c.testYieldsKt)].sort((a, b) => a - b)
}

const out = `// AUTO-GENERATED by scripts/build-countries.mjs — do not edit by hand.
// Source of truth: research/country-facts.csv (verified rows only; chat-sourced
// 2026-10-22). Candidate and gap rows are excluded. Regenerate:
// node scripts/build-countries.mjs
export type CountryRow = {
  field: string
  value: string
  unit: string
  asOf: string
  sourceId: string
  deepUrl: string
  quote: string
  notes: string
}
export type Country = {
  slug: string
  key: string
  name: string
  article: string
  demonym: string
  rows: CountryRow[]
  warheadYieldsKt: number[]
  testYieldsKt: number[]
}

export const COUNTRY_SLUGS: string[] = ${JSON.stringify(ORDER)}

export const COUNTRIES: Record<string, Country> = ${JSON.stringify(countries, null, 2)}
`
writeFileSync('src/lib/data/countries.ts', out)
const summary = ORDER.map((k) => `${k}: ${countries[k].rows.length} rows, warhead[${countries[k].warheadYieldsKt.join(',')}], test[${countries[k].testYieldsKt.join(',')}]`)
console.log('countries.ts written:\n' + summary.join('\n'))
