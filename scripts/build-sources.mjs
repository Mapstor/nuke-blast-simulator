// NBS-005: generate src/lib/data/sources.ts from the chat-verified source
// registries. Merges research/sources.csv (citable sources, 240) with the 8
// data-domain entries in research/data-sources.csv (engine + data sources,
// keyed by `domain`, e.g. effects-fireball). Re-run whenever a CSV changes.
import { writeFileSync } from 'node:fs'
import { readCsvObjects } from './lib/csv.mjs'

const sources = readCsvObjects('research/sources.csv')
const dataSources = readCsvObjects('research/data-sources.csv')

/** @type {Record<string,{publisher:string,title:string,url:string,attribution:string}>} */
const map = {}

for (const s of sources) {
  if (!s.id) continue
  map[s.id] = { publisher: s.publisher, title: s.title, url: s.url, attribution: s.attribution }
}
// Data-domain sources (effects-fireball, effects-blast-thermal, arsenals-2026, …).
for (const d of dataSources) {
  if (!d.domain) continue
  map[d.domain] = { publisher: d.publisher, title: d.source, url: d.url, attribution: d.attribution }
}

const ids = Object.keys(map).sort()
const dupNote = ids.length !== new Set(ids).size ? ' // WARNING: duplicate ids' : ''

const body = ids
  .map((id) => {
    const s = map[id]
    const esc = (v) => JSON.stringify(v ?? '')
    return `  ${JSON.stringify(id)}: { publisher: ${esc(s.publisher)}, title: ${esc(s.title)}, url: ${esc(s.url)}, attribution: ${esc(s.attribution)} },`
  })
  .join('\n')

const out = `// AUTO-GENERATED by scripts/build-sources.mjs — do not edit by hand.
// Source of truth: research/sources.csv + research/data-sources.csv (chat-verified).
export interface Source {
  publisher: string
  title: string
  url: string
  attribution: string
}

export const SOURCES: Record<string, Source> = {${dupNote}
${body}
}

export function getSource(id: string): Source | undefined {
  return SOURCES[id]
}
`

writeFileSync('src/lib/data/sources.ts', out)
console.log(`sources.ts: ${ids.length} sources (${sources.length} from sources.csv + ${dataSources.length} data-domain)`)
